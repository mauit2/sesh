// Build supabase/seeds/venues.sql from PUBLIC data so the local maps have
// bars on them. Reads only what any anonymous client can already read:
// the venues table, the aggregated beer prices, and the sun profiles of the
// biggest cities. Writes no personal data (no reporters, no QR tokens).
//
// Run (explicitly against production; it never defaults there):
//   SUPA_URL=https://<project>.supabase.co SUPA_ANON=<anon key> node scripts/seed-venues.mjs
// Then `supabase db reset` applies the file after the migrations.

import { writeFileSync } from "node:fs";

const SUPA_URL = process.env.SUPA_URL;
const KEY = process.env.SUPA_ANON;
if (!SUPA_URL) { console.error("SUPA_URL not set"); process.exit(1); }
if (!KEY) { console.error("SUPA_ANON not set"); process.exit(1); }
const REST = SUPA_URL.replace(/\/$/, "") + "/rest/v1";
const H = { apikey: KEY, Authorization: `Bearer ${KEY}`, "Content-Type": "application/json" };

async function get(path, extra = {}) {
  const r = await fetch(`${REST}/${path}`, { headers: { ...H, ...extra } });
  if (!r.ok) throw new Error(`${path}: HTTP ${r.status} ${await r.text()}`);
  return r.json();
}
async function rpc(name, body) {
  const r = await fetch(`${REST}/rpc/${name}`, { method: "POST", headers: H, body: JSON.stringify(body) });
  if (!r.ok) throw new Error(`rpc ${name}: HTTP ${r.status} ${await r.text()}`);
  return r.json();
}

const q = (v) => v === null || v === undefined ? "null"
  : typeof v === "number" ? String(v)
  : typeof v === "boolean" ? (v ? "true" : "false")
  : Array.isArray(v) ? `'{${v.join(",")}}'`
  : `'${String(v).replace(/'/g, "''")}'`;

// 1. Venues, paged (PostgREST caps a response at 1000 rows).
const cols = "id,name,address,city,lat,lon,source,external_id,country,kind,prominence,outdoor_seating,time_zone,created_at";
const venues = [];
for (let from = 0; ; from += 1000) {
  const page = await get(`venues?select=${cols}&order=id`, { Range: `${from}-${from + 999}` });
  venues.push(...page);
  if (page.length < 1000) break;
}
console.error(`venues: ${venues.length}`);

// 2. Aggregated prices → one synthetic 'curated' row per venue + serving.
const prices = [];
for (let off = 0; ; off += 1000) {
  const page = await rpc("public_beer_prices", { p_limit: 1000, p_offset: off });
  prices.push(...page);
  if (page.length < 1000) break;
}
console.error(`price rows: ${prices.length}`);

// 3. Sun profiles around the biggest cities (the RPC caps at 400 per call).
const cities = [
  ["Göteborg", 57.7089, 11.9746], ["Stockholm", 59.3293, 18.0686], ["Malmö", 55.605, 13.0038],
  ["Uppsala", 59.8586, 17.6389], ["Berlin", 52.52, 13.405], ["London", 51.5074, -0.1278],
  ["Munich", 48.1351, 11.582], ["Amsterdam", 52.3676, 4.9041], ["Dublin", 53.3498, -6.2603],
  ["Paris", 48.8566, 2.3522],
];
const sun = new Map();
for (const [name, lat, lon] of cities) {
  const rows = await rpc("venue_sun_map", { p_lat: lat, p_lon: lon, p_radius_m: 25000, p_limit: 400, p_min_prominence: 0 });
  for (const r of rows) sun.set(r.venue_id, r);
  console.error(`sun ${name}: ${rows.length}`);
}

// 4. Write SQL. ON CONFLICT DO NOTHING so a re-run is harmless.
const out = [];
out.push("-- Generated by scripts/seed-venues.mjs from public data on " + new Date().toISOString().slice(0, 10) + ". Local only.");
out.push("-- Venues, aggregated prices as synthetic 'curated' rows, and sun profiles for ten cities.");
const batch = (rows, fn, head) => {
  for (let i = 0; i < rows.length; i += 500) {
    out.push(head + "\n" + rows.slice(i, i + 500).map(fn).join(",\n") + "\non conflict do nothing;");
  }
};
batch(venues, (v) => `(${[v.id, v.name, v.address, v.city, v.lat, v.lon, v.source, v.external_id, v.country, v.kind, v.prominence, v.outdoor_seating, v.time_zone, v.created_at].map(q).join(",")})`,
  "insert into public.venues (id,name,address,city,lat,lon,source,external_id,country,kind,prominence,outdoor_seating,time_zone,created_at) values");
const venueIds = new Set(venues.map((v) => v.id));
batch(prices.filter((p) => venueIds.has(p.venue_id)), (p) => `(${[p.venue_id, p.price, p.serving, p.currency, "curated", p.last_reported ?? null].map(q).join(",")})`,
  "insert into public.beer_prices (venue_id,price_sek,serving,currency,source,created_at) values");
batch([...sun.values()].filter((s) => venueIds.has(s.venue_id)), (s) => `(${[s.venue_id, s.horizon, s.confidence, "seed", s.facade_bearing, s.facade_reports ?? 0].map(q).join(",")}, now())`,
  "insert into public.venue_sun (venue_id,horizon,confidence,source,facade_bearing,facade_reports,computed_at) values");
writeFileSync("supabase/seeds/venues.sql", out.join("\n\n") + "\n");
console.error(`wrote supabase/seeds/venues.sql (${venues.length} venues, ${prices.length} prices, ${sun.size} sun profiles)`);
